        <h2>Times that have already changed</h2>
        <p><strong>Chana masala, twelve to fifteen minutes.</strong> Four readers in the same
          month said it took them closer to eighteen, and all four mentioned the onion. I had
          been dicing an onion in about ninety seconds because I do it constantly; a reasonable
          person takes three minutes. The prep number went up and a dated line at the foot of
          the recipe says so.</p>
        <p><strong>Sheet-pan gnocchi, fifteen to twenty minutes.</strong> The original number
          excluded the oven preheating, which is indefensible when the oven is the entire
          method. The preheat is now stated separately and the total is honest.</p>
        <p>Both of those came from readers rather than from me noticing, which is the whole
          argument for this page existing.</p>
      </div>
      <div>
        <h2>What I cannot answer</h2>
        <p>Substitutions I have not cooked. If you ask whether tofu works in the chilli paneer
          I will say I do not know, because I have not tried it, and a guess costs you a dinner
          rather than costing me anything.</p>
        <p>Anything dietary or medical. I am not a dietitian, and the nutrition figures here
          are estimates, which the <a href="../policies/disclaimer.php">disclaimer</a>
          explains at length. If you have an allergy, read the packet rather than trusting my
          allergen note, which describes the ingredients as I wrote them.</p>
        <p>Whether a recipe is authentic. The chana masala is a weeknight version and the page
          says so in its first sentence. The chilli paneer is Indo-Chinese, which is its own
          real tradition rather than a compromise. Neither claims to be anybody's grandmother's
          recipe and I am not going to pretend otherwise for the sake of a better story.</p>
      </div>
    </div>
