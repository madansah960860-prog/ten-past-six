<section class="band band--tight">
  <div class="wrap">
    <div class="prose">
      <p>I worked nights for six years. Warehouse shifts, then dispatch, then a stretch at a
        distribution center on the far west side where I finished at half past five in the
        morning and slept until two in the afternoon.</p>
      <p>What that does to cooking is specific and nobody writes about it. You are hungry at a
        time when you have no energy left to decide anything. You stand in front of the
        refrigerator at some equivalent of ten past six and you can either cook, or eat
        something out of a packet, and the deciding factor is almost never whether you know
        how to cook. It is whether you can face finding out how long it will take.</p>
      <p>So I started timing things. Properly, with a stopwatch, because the numbers on recipe
        sites are fantasy. A recipe that says "20 minutes" and then opens with "finely dice
        one onion, two carrots and a stick of celery" has already spent eight of them before
        the pan is hot, and the person who cooks it feels slow rather than lied to.</p>

      <h2>How the times are measured</h2>
      <p>The stopwatch starts when I walk into the kitchen and stops when the food is on the
        table. It includes everything. Getting the board out. Chopping. Waiting for water. The
        forty seconds spent looking for the soy sauce that was behind the vinegar.</p>
      <p>Each recipe gets cooked four times. Two of those are timed. Then Deb, who lives
        downstairs and cooks perfectly well but has not read the draft before, cooks it cold
        from the printed page with a timer running and no help from me.</p>
      <p>If her time comes out over the number on the card, the number changes. It has changed
        on four of the six recipes here, always upward. Chilli paneer went from ten to fifteen.
        The gnocchi went from fifteen to twenty. Nothing has ever gone down.</p>

      <h2>Why only six</h2>
      <p>Because that process takes about three weeks per recipe and I have a job.</p>
      <p>Also because six is roughly the number of weeknight dinners a person actually needs.
        Nobody cooks from a library of four hundred recipes. They cook from a rotation of five
        or six things they know cold, and the useful thing a site can do is get one or two
        genuinely reliable dishes into that rotation.</p>
      <p>When a seventh is finished it will go up. There is no schedule.</p>

      <h2>What this site does not do</h2>
      <p>No story before the recipe. The headnote is two sentences and then the method starts.
        The reason other sites do it is search ranking, and I would rather rank badly.</p>
      <p>No JavaScript at all. Not a preference, a decision: the filter on the recipe index is
        built out of CSS and the <code>:target</code> selector, which means nothing on this
        page moves, jumps, reflows or loads late. If you have ever tried to tap a recipe link
        and hit an advertisement that appeared under your thumb, that is the problem this
        solves.</p>
      <p>No sponsored recipes, no affiliate links, no gifted equipment written up as a review.
        This site is paid for by the display advertising in the slots marked
        "Advertisement", and that is the whole arrangement. See the
        <a href="../policies/advertising-disclosure.php">advertising disclosure</a>.</p>

      <h2 id="photographs">About the pictures</h2>
      <p>They are licensed stock photographs, not pictures of my cooking. I am not going to
        pretend otherwise, and no caption on this site says a photograph is something it is
        not.</p>
      <p>The reason is straightforward: a recipe that takes ten minutes does not survive being
        photographed properly, and the apartment has one window. Every image is listed with
        its source and licence in <code>assets/images/CREDITS.txt</code>.</p>
      <p>What matters on a fast recipe is not a picture anyway. It is the cue written into the
        step, which is why the fried rice tells you to listen for a crackle and the paneer
        tells you it will release from the pan by itself. Those are more useful than a photo
        of somebody else's pan.</p>

      <h2>The kitchen</h2>
      <p>A third-floor walk-up on Belmont with four feet of counter, a four-burner gas stove
        where the back left burner is significantly weaker than the others, and an oven that
        runs hot. Every recipe here was developed in that kitchen, which is deliberately not a
        good one. If it works here it will work in yours.</p>
      <p>The widest pan I own is twelve inches. Several recipes say to use your widest pan and
        that is the one I mean.</p>
    </div>
