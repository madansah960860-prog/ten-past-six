      <div>
        <h2>How the filter works</h2>
        <p>Clicking a time puts a fragment on the URL, the CSS notices it with the
          <code>:target</code> selector, and the groups that do not match get set to
          <code>display: none</code>. That is the whole mechanism and it is about eight lines
          of stylesheet.</p>
        <p>The point is not cleverness. It is that a filter built this way costs nothing to
          load, works before any script would have run, works with a script blocker on, and
          cannot make the page jump while you are reaching for a link. Most filters on recipe
          sites do all four of those things badly.</p>
        <p>The one honest limitation: the browser scrolls to the target when you click, and
          there is no way to stop that without a script. We have put the targets immediately
          above the filter so the jump is barely noticeable.</p>
      </div>
      <div>
        <h2>Why only three bands</h2>
        <p>Ten, fifteen, twenty. Nothing on this site takes longer, and dividing twenty
          minutes into finer slices would be false precision, because your onion is a
          different size from mine.</p>
        <p>The bands are deliberately the pessimistic number rather than the optimistic one. A
          recipe that Deb cooked in thirteen minutes goes in the fifteen band, not the ten.
          There is nothing here that will take you longer than the number says, which is the
          opposite of how recipe timings normally work.</p>
        <p>If you have more than twenty minutes, you do not need this website, and there are
          better ones for that. <a href="../pages/about.php">Why the site is like
          this</a>.</p>
      </div>
    </div>
  </div>
</section>

