      <div>
        <h2>What all six have in common</h2>
        <p><strong>One pan, or none.</strong> Five of the six use a single pan and the sixth
          uses no heat at all. Nothing here asks you to run two pans at once, because at speed
          that is exactly where things go wrong.</p>
        <p><strong>Nothing needs an unusual ingredient.</strong> Everything on these six lists
          is available in an ordinary supermarket, and most of it keeps in a cupboard for
          months.</p>
        <p><strong>Every quantity was weighed.</strong> Grams first, cups converted afterward
          from the weight. That direction matters: going the other way bakes in whatever size
          onion happened to be on the counter that day.</p>
        <p><strong>Every step has a cue you can see or hear.</strong> Not cook until done. The
          fried rice step says you are listening for a steady crackle, because a timer cannot
          tell you whether your burner is hot enough and your ears can.</p>
      </div>
      <div>
        <h2>The three that scale</h2>
        <p>Chana masala, sheet-pan gnocchi and the bean salad all double cleanly. Two cans
          become four, one tray becomes two, and nothing else changes except that the gnocchi
          needs a second tray rather than a fuller one.</p>
        <p>The three stir-fried recipes do not double. Twice the volume in the same pan drops
          the temperature, and a stir-fry that is not hot enough becomes a steam-fry with
          exactly the limp texture you were trying to avoid. Cook those twice in sequence, or
          use two pans, and accept that it is no longer a ten-minute dinner.</p>
        <p>This is the sort of thing a recipe site usually leaves out, because serves two,
          easily doubled reads better than the truth. It is not easily doubled. It is easily
          cooked twice.</p>
      </div>
    </div>
