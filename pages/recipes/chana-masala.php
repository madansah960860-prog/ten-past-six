      <div>
        <h2>Method</h2>
        <ol class="method">
      <li><div><p>Heat the oil in a wide pan over medium-high heat. Add the cumin seeds and let them sizzle for twenty seconds until they smell toasted.</p></div></li>
      <li><div><p>Add the onion and cook for four minutes, stirring, until softened and starting to color at the edges. Four minutes is not enough for properly caramelized onion and that is the honest compromise this recipe makes.</p></div></li>
      <li><div><p>Add the garlic, ginger and green chilli and cook for one minute.</p></div></li>
      <li><div><p>Add the coriander, turmeric and Kashmiri chilli. Stir for thirty seconds only, over lower heat; ground spices scorch fast.</p></div></li>
      <li><div><p>Tip in the tomatoes. Turn the heat up and cook hard for four to five minutes, stirring and squashing, until the mixture darkens and you can see oil coming out at the edges. That separation is the signal that the tomato is cooked rather than raw.</p></div></li>
      <li><div><p>Add the chickpeas and the salt with a splash of water, maybe 100 ml. Simmer for four minutes, pressing about a quarter of the chickpeas against the side of the pan with the back of a spoon. Those broken ones thicken the whole thing.</p></div></li>
      <li><div><p>Off the heat, stir in the garam masala, the lemon juice and most of the cilantro. Taste for salt and sharpness. Serve with rice, or with bread, and the rest of the cilantro on top.</p></div></li>
        </ol>

        <h2 class="mt6">Allergens</h2>
        <div class="note">
          <p>Free from all fourteen major allergens as written, if you use oil rather than ghee. Check the canned tomatoes and the chilli powder, as some blends contain anti-caking agents derived from wheat.</p>
          <p><strong>Read the labels yourself.</strong> This note describes the ingredients as
            written, not the packets in your kitchen, and formulations change without
            notice.</p>
        </div>

        <h2 class="mt6">Storage</h2>
        <div class="note">
          <p>Refrigerate within two hours for up to four days and it genuinely improves overnight. Freezes for three months. Reheat on the stovetop with a splash of water until piping hot throughout.</p>
        </div>

