      <div>
        <h2>Method</h2>
        <ol class="method">
      <li><div><p>Heat the oven to 425&#176;F with a large shallow baking tray inside it. The tray needs to be properly hot before anything touches it.</p></div></li>
      <li><div><p>While it heats, toss the gnocchi, tomatoes, onion wedges and garlic cloves in a bowl with the olive oil, oregano, chilli flakes, salt and pepper.</p></div></li>
      <li><div><p>Pull the hot tray out and tip everything onto it in a single layer. It should hiss. Spread it out so nothing is piled up; two trays are better than one crowded one.</p></div></li>
      <li><div><p>Roast for twelve minutes without touching it.</p></div></li>
      <li><div><p>Take the tray out and shake it or turn things with a spatula. The gnocchi should be blistered and golden on the underside and the tomatoes should have started to burst.</p></div></li>
      <li><div><p>If you are using mozzarella, tear it over now. Return to the oven for three to five more minutes until the cheese has melted and the tomatoes have collapsed.</p></div></li>
      <li><div><p>Squeeze the softened garlic out of its skins and stir it through. Scatter with basil, grind over pepper, and serve straight from the tray.</p></div></li>
        </ol>

        <h2 class="mt6">Allergens</h2>
        <div class="note">
          <p>Contains wheat (gnocchi almost always contains wheat flour) and milk (mozzarella; leave it out to avoid). Check the gnocchi packet, as some brands contain egg.</p>
          <p><strong>Read the labels yourself.</strong> This note describes the ingredients as
            written, not the packets in your kitchen, and formulations change without
            notice.</p>
        </div>

        <h2 class="mt6">Storage</h2>
        <div class="note">
          <p>Eat the same evening. Roasted gnocchi loses its crisp edge completely in the refrigerator. If you have leftovers, refry them in a hot pan rather than reheating in the oven, and expect them to be softer.</p>
        </div>

