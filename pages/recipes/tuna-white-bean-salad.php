      <div>
        <h2>Method</h2>
        <ol class="method">
      <li><div><p>Slice the onion as thinly as you can and drop it into a bowl of cold water. Leave it there while you do everything else. Five minutes is the minimum and ten is better.</p></div></li>
      <li><div><p>Drain and rinse the beans properly, until the water runs clear. The liquid in the can tastes of the can, and rinsing is the single biggest improvement available here.</p></div></li>
      <li><div><p>Tip the beans into a bowl. Add the lemon zest and juice, the olive oil, the oil from the tuna, the salt and a great deal of black pepper. Stir and leave for two minutes; the beans absorb the dressing rather than sitting in it.</p></div></li>
      <li><div><p>Drain the onion thoroughly, pressing it in a sieve, and add it with the capers.</p></div></li>
      <li><div><p>Add the tuna last and fold it through in large flakes. Do not stir hard or you will end up with paste.</p></div></li>
      <li><div><p>Stir in the parsley, taste, and add more lemon or salt. It should be noticeably sharper than feels right in the bowl, because beans flatten out as they sit. Eat with bread.</p></div></li>
        </ol>

        <h2 class="mt6">Allergens</h2>
        <div class="note">
          <p>Contains fish. Free from wheat, milk, egg, soy and nuts as written. Check the tuna can, as some brands pack in broth containing soy.</p>
          <p><strong>Read the labels yourself.</strong> This note describes the ingredients as
            written, not the packets in your kitchen, and formulations change without
            notice.</p>
        </div>

        <h2 class="mt6">Storage</h2>
        <div class="note">
          <p>Keeps two days in the refrigerator and is arguably better on day two, once the beans have taken on the dressing. Add the parsley fresh when you serve it rather than storing it in. Do not freeze.</p>
        </div>

