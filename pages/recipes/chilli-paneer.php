      <div>
        <h2>Method</h2>
        <ol class="method">
      <li><div><p>Chop everything first. All of it. Put the sauce ingredients in one small bowl together, except the cornstarch slurry which goes in its own. From the moment the pan is hot you have about seven minutes and no hands free.</p></div></li>
      <li><div><p>Pat the paneer completely dry with paper towels, then toss it with the cornstarch until every side is dusted.</p></div></li>
      <li><div><p>Heat the oil in a wide pan or wok over medium-high heat until it shimmers. Add the paneer in one layer and leave it alone for three minutes. It should release by itself when it is properly browned.</p></div></li>
      <li><div><p>Turn and give it another two minutes, then lift it out onto a plate. It will not be crisp on every side and that is fine.</p></div></li>
      <li><div><p>Turn the heat to high. Add the onion and pepper to the same pan and stir-fry hard for ninety seconds. You want them blistered at the edges and still crunchy in the middle.</p></div></li>
      <li><div><p>Add the garlic, ginger and chillies and stir for thirty seconds until fragrant.</p></div></li>
      <li><div><p>Pour in the combined sauce. It will spit. Let it bubble for thirty seconds, then stir in the cornstarch slurry and cook for another thirty until it thickens and goes glossy.</p></div></li>
      <li><div><p>Return the paneer, add the scallions, and toss for thirty seconds so everything is coated. Serve immediately, while the vegetables still have bite.</p></div></li>
        </ol>

        <h2 class="mt6">Allergens</h2>
        <div class="note">
          <p>Contains milk (paneer), soy and wheat (soy sauce usually contains wheat; tamari does not). Check the ketchup, which sometimes contains celery.</p>
          <p><strong>Read the labels yourself.</strong> This note describes the ingredients as
            written, not the packets in your kitchen, and formulations change without
            notice.</p>
        </div>

        <h2 class="mt6">Storage</h2>
        <div class="note">
          <p>Best within the hour. Refrigerate for up to two days; the paneer softens and the vegetables lose their crunch. Reheat in a hot pan rather than a microwave, which makes paneer rubbery.</p>
        </div>

