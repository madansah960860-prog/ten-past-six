      <div>
        <h2>Method</h2>
        <ol class="method">
      <li><div><p>Break the cold rice up with your fingers in the bowl until there are no clumps. Two minutes of this makes an enormous difference and there is no shortcut.</p></div></li>
      <li><div><p>Heat a tablespoon of the oil in your widest pan over high heat until it is genuinely smoking. Pour in the eggs, let them set for fifteen seconds, then scramble hard for twenty more until just done. Tip them out onto a plate.</p></div></li>
      <li><div><p>Add the rest of the oil to the pan, still on high. Add the garlic and the scallion whites and stir for fifteen seconds.</p></div></li>
      <li><div><p>Add the rice all at once. Press it flat against the pan for twenty seconds, then toss and press again. Keep doing this for two to three minutes. You are listening for a steady crackle; if it goes quiet, the pan is not hot enough.</p></div></li>
      <li><div><p>Add the frozen peas straight from the freezer and toss for a minute until heated through.</p></div></li>
      <li><div><p>Return the egg, breaking it into pieces. Add the soy sauce around the edge of the pan rather than into the middle, so it hits hot metal and caramelizes rather than steaming the rice.</p></div></li>
      <li><div><p>Off the heat, add the sesame oil, the white pepper and the scallion greens. Toss once and serve immediately.</p></div></li>
        </ol>

        <h2 class="mt6">Allergens</h2>
        <div class="note">
          <p>Contains egg, soy and wheat (soy sauce). Contains sesame. Free from milk and nuts as written.</p>
          <p><strong>Read the labels yourself.</strong> This note describes the ingredients as
            written, not the packets in your kitchen, and formulations change without
            notice.</p>
        </div>

        <h2 class="mt6">Storage</h2>
        <div class="note">
          <p>Eat immediately. Rice that has been cooked, cooled and reheated should only be reheated once, and should be piping hot throughout. Rice kept warm or cooled slowly can grow Bacillus cereus, so cool leftovers fast and refrigerate within one hour.</p>
        </div>

