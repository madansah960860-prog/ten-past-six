      <div>
        <h2>Method</h2>
        <ol class="method">
      <li><div><p>Put the noodles on in well-salted boiling water. Set a timer for one minute less than the packet says. Everything else happens while they cook.</p></div></li>
      <li><div><p>Melt the butter in a wide pan over LOW heat. Low, not medium. Add the garlic and chilli flakes and cook for sixty to ninety seconds, until the garlic is pale gold and smells sweet. If it browns, start again; bitter garlic ruins the whole pan.</p></div></li>
      <li><div><p>Take a mug of the noodle water out of the pot before you drain. This is the step people forget and it is what makes the sauce.</p></div></li>
      <li><div><p>Drain the noodles and tip them straight into the butter pan. Add the soy sauce and a good splash of the noodle water, maybe 60 ml.</p></div></li>
      <li><div><p>Turn the heat up to medium and toss hard for sixty to ninety seconds. The starch in the water emulsifies with the butter and goes from a puddle to a glossy sauce that clings. Add more water a splash at a time if it tightens.</p></div></li>
      <li><div><p>Off the heat, add the scallions, Parmesan if using, and plenty of black pepper. Toss once more and eat straight away, from the pan if you like.</p></div></li>
        </ol>

        <h2 class="mt6">Allergens</h2>
        <div class="note">
          <p>Contains wheat, egg (in egg noodles), milk (butter, Parmesan) and soy. Soy sauce almost always contains wheat; tamari is the gluten-free swap.</p>
          <p><strong>Read the labels yourself.</strong> This note describes the ingredients as
            written, not the packets in your kitchen, and formulations change without
            notice.</p>
        </div>

        <h2 class="mt6">Storage</h2>
        <div class="note">
          <p>Eat now. Noodles in an emulsified butter sauce do not reheat well: the sauce breaks and the noodles go slack. If you must, keep for one day and revive in a pan with a splash of water rather than a microwave.</p>
        </div>

