      <div>
        <h2>By what is in the house</h2>
        <p><strong>Nothing fresh at all.</strong> Garlic butter noodles, or the tuna and bean
          salad. Both are entirely pantry apart from one onion or a few scallions.</p>
        <p><strong>Yesterday's rice.</strong> Egg fried rice, and nothing else. Do not make
          rice specially for it; the point is that the rice already exists.</p>
        <p><strong>Two cans of chickpeas.</strong> Chana masala, which is the cheapest dinner
          on this site by a wide margin and feeds three.</p>
      </div>
      <div>
        <h2>By who you are feeding</h2>
        <p><strong>Just you.</strong> Halve the noodles. Everything else scales badly downward
          because a half-full pan browns differently.</p>
        <p><strong>Two of you.</strong> Every recipe here is written for two or three, which is
          not an accident.</p>
        <p><strong>Four or more.</strong> Chana masala and sheet-pan gnocchi double cleanly.
          The stir-fries do not: doubling a stir-fry in one pan turns it into a steam-fry.
          Cook it twice or use two pans.</p>
      </div>
    </div>
