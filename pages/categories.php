    <div class="note mt6 measure">
      <h3>What the extra five minutes buys</h3>
      <p>The ability to build a base. Five minutes is roughly what it takes to soften an
        onion, bloom ground spices without scorching them, and cook a tomato out until the oil
        separates. That last step is why the chana masala tastes cooked rather than raw, and
        it is the entire difference between the ten and fifteen minute bands.</p>
    </div>
