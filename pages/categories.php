      <p>Twenty minutes with an oven is less work than ten minutes at a stovetop, because
        twelve of them are hands-off. If you are tired rather than in a hurry, the sheet-pan
        gnocchi is the easiest thing on this site despite having the largest number on the
        card. The number measures elapsed time, not effort, and those are not the same
