<h1>Editorial Policy</h1>
<p class="lede">This page sets out how content on www.tenpastsix.com is made and who is accountable for it. It exists because a reader deciding whether to trust a website deserves to know the answer rather than guess at it.</p>
<p class="stamp">Last updated 1 September 2026.</p>

<h2>Who writes this site</h2>
<p>Ten Past Six is written by named people. Marcus Obi, writer, cook and the person holding the stopwatch, is the editor and writes the majority of what appears here. One person. Marcus cooks each recipe at least four times, twice against a stopwatch, and a neighbor called Deb cooks the final draft cold with no explanation and a timer running. If her time comes out over the number on the card, the number on the card changes.</p>
<p>Every substantial page carries the name of the person who wrote it. Where a page was written by one person and reviewed by another, both names appear. We do not publish under a house byline, we do not invent contributor personas, and there is no artificial intelligence writing the words on this site.</p>
<h2>How a recipe gets onto this site</h2>
<p>Every recipe here is cooked before it is published, in a domestic kitchen, by the person whose name is on it. Nothing is adapted from another publication, generated automatically, or written from an idea of how a dish probably goes. The working process is the same each time.</p>
<ol>
  <li><strong>Cook it.</strong> First pass, writing down what was actually done rather than what was planned, including the mistakes.</li>
  <li><strong>Weigh it.</strong> Second pass with scales out. Every ingredient recorded in grams and milliliters, then converted to cups and spoons afterwards rather than the other way round, because the conversion in that direction is the one that survives.</li>
  <li><strong>Cook it again.</strong> Third pass following the written draft exactly, to find the step that made sense in the cook's head and nowhere else.</li>
  <li><strong>Hand it to somebody else.</strong> Where possible a second cook works from the draft with no verbal explanation. Their questions become the clarifications.</li>
  <li><strong>Check the numbers.</strong> Times, temperatures, yields and pan sizes are checked against what was recorded, not against memory.</li>
</ol>
<p>Nutrition estimates are generated from ingredient databases and are labeled as estimates everywhere they appear. Allergen notes are written from the ingredient list as published and carry an instruction to check labels, because formulations change and ours is not the packet in your hand.</p>

<h2>Claims we will not make</h2>
<ul>
  <li>That any food cures, treats or prevents a disease.</li>
  <li>That a recipe will produce weight loss of any amount in any period.</li>
  <li>That an ingredient is a detox, a superfood, or a substitute for medical care.</li>
  <li>That a regional dish is the one authentic version of itself, when regional dishes almost never are.</li>
  <li>Any nutrition figure presented as exact rather than estimated.</li>
</ul>

<h2>Independence from advertising</h2>
<p>The advertising on this site is served automatically and nobody here sees an advertiser's name before it appears. No advertiser has ever been shown a draft, has ever suggested a topic, or has any right of review over anything published. If that changed, this page would change with it and the arrangement would be disclosed on the page in question. Our <a href="advertising-disclosure.php">Advertising Disclosure</a> covers the commercial side in detail.</p>

<h2>Sources and attribution</h2>
<p>Where we rely on someone else's work we say so and link to it. Quotations are short, marked and attributed. Photographs are credited in the image credits file that ships with the site, each with a source link and its license. Where an idea came from a particular teacher, book or region, that lineage is named, because pretending otherwise is both dishonest and duller.</p>

<h2>Corrections</h2>
<p>We correct mistakes rather than quietly deleting them. The scale of the response matches the scale of the error.</p>
<ul>
  <li><strong>Typographical and formatting errors</strong> are fixed on sight without a note.</li>
  <li><strong>Factual errors that change the meaning</strong> are fixed, and a dated correction line is added at the foot of the page saying what was wrong and what it now says.</li>
  <li><strong>Errors that could cause harm</strong>, such as a wrong temperature, a wrong quantity or an unsafe instruction, are fixed immediately, flagged at the top of the page, and the page is re-checked from the beginning.</li>
  <li><strong>Articles that are simply out of date</strong> are either updated with a new review date or retired with a note explaining why.</li>
</ul>

<h2>How to request a correction</h2>
<p>Email <a href="mailto:fix@tenpastsix.com">fix@tenpastsix.com</a> with the page address and the specific sentence you think is wrong. If you have a source, include it. We acknowledge correction requests within three business days and act on valid ones within seven. If we disagree with you we will say so and explain why rather than ignore the message. If you were right, the correction line will say that a reader pointed it out, and you are welcome to be named or to stay anonymous as you prefer.</p>

<h2>Review cycle</h2>
<p>Published pages are reviewed on a rolling basis, with the practical pages that people act on prioritized over the reflective ones. Each reviewed page carries the date it was last checked. A review date is not decoration: it means somebody read the page again with fresh eyes and confirmed that it still says what it should.</p>
