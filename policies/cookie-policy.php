<h1>Cookie Policy</h1>
<p class="lede">Cookies are small text files stored by your browser at a website's request and handed back on subsequent visits. They are how a site remembers anything at all. This page lists the categories in use on www.tenpastsix.com, explains what each one is for, and tells you how to refuse them.</p>
<p class="stamp">Last updated 1 September 2026.</p>

<h2>The short version</h2>
<p>Ten Past Six sets no first-party tracking cookies. Everything described below is either strictly necessary for the page to work or is placed by a third-party advertising or measurement service. If you block third-party cookies entirely, this website continues to function normally. Nothing on it is gated behind a cookie.</p>

<h2>Category one: strictly necessary</h2>
<p>These make the site work and cannot be switched off from within the site. In our case the category is almost empty, because the pages are static documents with no login and no basket. What remains are the security and load-balancing cookies our hosting provider and content delivery network may set to route your request to a working server and to distinguish a human visitor from an automated one mounting an attack.</p>
<ul>
  <li><strong>Purpose:</strong> routing, fraud prevention, denial-of-service protection.</li>
  <li><strong>Typical lifetime:</strong> the browsing session, or up to 24 hours.</li>
  <li><strong>Consent:</strong> not required under the ePrivacy Directive, because they are strictly necessary to deliver a service you asked for.</li>
</ul>

<h2>Category two: analytics and performance</h2>
<p>Analytics cookies tell us how many people read a page, roughly where in the world they are, which page sent them, and whether they left immediately. We use this to decide what to write next and to notice when something is broken. Analytics data is aggregated; we do not look at individuals, and we could not identify you from it if we wanted to.</p>
<ul>
  <li><strong>Purpose:</strong> audience measurement, page performance, error detection.</li>
  <li><strong>Typical lifetime:</strong> from one session up to two years, depending on the provider.</li>
  <li><strong>Consent:</strong> required in the EEA and the UK, and requested through the consent notice presented on your first visit.</li>
</ul>

<h2>Category three: advertising</h2>
<p>This is the category that pays for the site. Advertising cookies are set by Google and by other advertising vendors whose technology appears in the reserved advertisement slots. They are used to select which advertisement to show, to stop you seeing the same advertisement twenty times, to measure whether an advertisement led to anything, and, where you have consented, to personalize what is shown based on your browsing across other sites.</p>
<ul>
  <li><strong>Purpose:</strong> ad selection, frequency capping, measurement, personalization.</li>
  <li><strong>Typical lifetime:</strong> from 30 days to 24 months.</li>
  <li><strong>Consent:</strong> required in the EEA and the UK. Withdrawing consent is possible at any time through the links in our <a href="privacy-policy.php">Privacy Policy</a>.</li>
  <li><strong>Note:</strong> Google's use of the DoubleClick DART cookie falls in this category, and can be declined through the Google advertising and content network privacy policy.</li>
</ul>

<h2>Third-party cookies in general</h2>
<p>A third-party cookie is one set by a domain other than the one in your address bar. Every advertising and measurement cookie described above is a third-party cookie. We do not control them, we cannot read them, and we cannot delete them on your behalf. What we can do is tell you they are there and point you at the controls, which is what this page is for.</p>
<p>Embedded content from other services, such as a map or a video player, can also set cookies when the page containing it loads. Where Ten Past Six embeds anything of that kind, it is noted on the page in question.</p>

<h2>How to disable cookies in your browser</h2>
<p>Every major browser lets you block cookies outright, block only third-party cookies, or clear what has already been stored. Blocking third-party cookies is the setting that matters most here, and it costs you nothing on this website.</p>
<ul>
  <li><strong>Google Chrome:</strong> Settings, then Privacy and security, then Third-party cookies. Choose to block third-party cookies, or block all cookies for this site through the padlock icon in the address bar.</li>
  <li><strong>Mozilla Firefox:</strong> Settings, then Privacy &amp; Security. Enhanced Tracking Protection set to Strict blocks cross-site cookies by default; the Cookies and Site Data panel clears what is stored.</li>
  <li><strong>Apple Safari on macOS:</strong> Safari menu, then Settings, then Privacy. Tick Prevent cross-site tracking, and use Manage Website Data to remove existing cookies.</li>
  <li><strong>Safari on iOS or iPadOS:</strong> Settings app, then Apps, then Safari. Turn on Prevent Cross-Site Tracking, and use Clear History and Website Data.</li>
  <li><strong>Microsoft Edge:</strong> Settings, then Cookies and site permissions, then Manage and delete cookies and site data. Tracking prevention can be set to Strict under Privacy, search, and services.</li>
  <li><strong>Android Chrome:</strong> three-dot menu, Settings, Site settings, Cookies.</li>
</ul>
<p>Browsers also offer a private or incognito window, which discards all cookies when the window closes. That is the simplest one-off option if you would rather not change any settings permanently.</p>

<h2>Do Not Track and Global Privacy Control</h2>
<p>Some browsers send a Do Not Track header. There is no agreed industry standard for honoring it and most advertising vendors ignore it. The Global Privacy Control signal is newer, is legally recognized in California, and is honored by a growing number of vendors. We pass both signals through unaltered; what happens next is a matter for the vendor rather than for us.</p>

