<h1>DMCA and Copyright Policy</h1>
<p class="lede">Ten Past Six respects the intellectual property of others and expects the same in return. If you believe material on www.tenpastsix.com infringes a copyright you own or control, this page explains exactly how to tell us, and what happens next.</p>
<p class="stamp">Last updated 1 September 2026.</p>

<h2>Our position</h2>
<p>Everything published here is intended to be either original work, licensed material used within the terms of its license, or material used with permission. Photographs come from stock libraries under their published licenses and are recorded, file by file, with a source link, in the image credits file shipped with the site. If something has slipped through in error, we want to know, and we would rather fix it quickly than argue about it.</p>
<p>We operate a repeat infringer policy. Contributors whose material is the subject of repeated valid notices do not continue to contribute.</p>

<h2>Filing a notice of claimed infringement</h2>
<p>Send your notice in writing to the designated agent named below. Under section 512(c)(3) of the United States Digital Millennium Copyright Act, a notice must include substantially all of the following, and a notice missing them may be ineffective.</p>
<ol>
  <li>A physical or electronic signature of a person authorized to act on behalf of the owner of an exclusive right that is allegedly infringed.</li>
  <li>Identification of the copyrighted work claimed to have been infringed. If multiple works at a single site are covered by one notification, a representative list of those works.</li>
  <li>Identification of the material that is claimed to be infringing or to be the subject of infringing activity, and information reasonably sufficient to let us locate it. A direct URL to the page, and where relevant the filename of the image, is the single most useful thing you can give us.</li>
  <li>Information reasonably sufficient to allow us to contact you: your name, mailing address, telephone number and email address.</li>
  <li>A statement that you have a good faith belief that use of the material in the manner complained of is not authorized by the copyright owner, its agent, or the law.</li>
  <li>A statement that the information in the notification is accurate, and, under penalty of perjury, that you are authorized to act on behalf of the owner of an exclusive right that is allegedly infringed.</li>
</ol>

<h2>Designated agent</h2>
<p class="addr">Copyright Agent, Ten Past Six<br>Ten Past Six<br>2219 West Belmont Avenue, Apt 3R<br>Chicago, IL 60618<br>United States<br>Email <a href="mailto:copyright@tenpastsix.com">copyright@tenpastsix.com</a></p>
<p>Please put "DMCA notice" in the subject line. Email reaches us fastest. A notice sent by mail will be acted on, but it will be slower.</p>

<h2>What we do when a notice arrives</h2>
<p>We acknowledge receipt, normally within two business days. We review the notice for completeness. Where the claim appears valid on its face we remove or disable access to the material expeditiously, and we notify whoever supplied it, passing on a copy of your notice. Removal at this stage is not an admission of infringement; it is what the safe harbor provisions require and it is also simply the courteous thing to do while a question is open.</p>

<h2>Counter-notification</h2>
<p>If your material was removed and you believe that removal was the result of a mistake or a misidentification, you may send a counter-notification to the same agent. Under section 512(g)(3) it must include substantially all of the following.</p>
<ol>
  <li>Your physical or electronic signature.</li>
  <li>Identification of the material that has been removed or disabled, and the location at which it appeared before removal.</li>
  <li>A statement under penalty of perjury that you have a good faith belief the material was removed or disabled as a result of mistake or misidentification.</li>
  <li>Your name, mailing address and telephone number.</li>
  <li>A statement that you consent to the jurisdiction of the Federal District Court for the judicial district in which your address is located, or, if your address is outside the United States, to the jurisdiction of any judicial district in which the service provider may be found, and that you will accept service of process from the person who filed the original notification or from their agent.</li>
</ol>
<p>On receiving a valid counter-notification we forward it to the original complainant. If they do not notify us within ten business days that they have filed an action seeking a court order to restrain the activity, the material may be restored.</p>

<h2>A warning about false claims</h2>
<p>Section 512(f) provides that any person who knowingly materially misrepresents that material is infringing, or that it was removed by mistake, may be liable for damages, including costs and legal fees, incurred by the alleged infringer, by any copyright owner, or by the service provider. Please satisfy yourself that you hold the rights you are asserting, and consider whether the use might be fair use or fair dealing, before you send anything.</p>

<h2>If you would rather not file a formal notice</h2>
<p>A formal notice is not always the proportionate response. If you are a photographer who has spotted an image of yours used without the credit you expected, or a writer who thinks a quotation went beyond fair dealing, send an ordinary email to <a href="mailto:copyright@tenpastsix.com">copyright@tenpastsix.com</a> describing the problem. We will correct, credit or remove as appropriate, usually the same week, without anybody needing to invoke a statute.</p>
