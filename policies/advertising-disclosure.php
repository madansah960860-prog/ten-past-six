<h1>Advertising Disclosure</h1>
<p class="lede">This website carries advertisements, and those advertisements are what keep it free to read. Here is exactly how that works.</p>
<p class="stamp">Last updated 1 September 2026.</p>

<h2>Display advertising</h2>
<p>www.tenpastsix.com is monetised with display advertising. The reserved slots in the page layout, each labeled "Advertisement", are filled by third-party advertising technology, principally Google's advertising network. We are paid on the basis of impressions and clicks. The exact advertisement you see is chosen automatically, in the fraction of a second while the page loads, by systems we neither operate nor inspect.</p>
<p>This has two consequences worth stating plainly. First, we do not know in advance what will appear next to an article, and two readers on the same page will often see different advertisements. Second, we do not endorse what appears. An advertisement on this site is not a recommendation from us, and you should apply the same skepticism to it that you would apply to an advertisement anywhere else.</p>
<p>The slots are given fixed reserved dimensions in the stylesheet so that the page does not jump while an advertisement loads. That is a deliberate design decision: nothing on this site moves under your finger as you go to tap it.</p>

<h2>Affiliate links</h2>
<p>Some outbound links to products are affiliate links. If you follow one and buy something, we may receive a small commission from the retailer, at no additional cost to you. The price you pay is the same as it would be if you had navigated there yourself.</p>
<p>Our rules for affiliate links are short and we keep to them. We only link to something we have actually used. We link to the thing we genuinely recommend, not to whichever program pays best. We do not stuff articles with links to manufacture opportunities. And an affiliate link never determines whether a piece gets written or what it concludes. Where a page contains affiliate links, it says so on the page, near the links, not only here.</p>

<h2>Sponsored content</h2>
<p>We do not currently publish sponsored articles, paid reviews, paid guest posts or paid link placements. If that ever changes, any such item will be labeled clearly at the top of the page, before the content, in the same typeface and at the same size as the rest of the page, using the words "Paid content" or "Sponsored". It will never be disguised as ordinary editorial. We do not sell links in existing articles, and requests to buy one are deleted unanswered.</p>

<h2>Gifts and review samples</h2>
<p>If something is sent to us free of charge, that fact is stated in any piece that mentions it. Receiving an item creates no obligation to write about it and no obligation to be kind about it. Items we do not rate do not get a favorable write-up, and most of the time they simply do not get written about at all.</p>

<h2>What advertising does not influence</h2>
<ul>
  <li>Which topics are covered, and in what order.</li>
  <li>What a piece concludes, including when the conclusion is unhelpful to a potential advertiser.</li>
  <li>Whether a correction is published.</li>
  <li>Which links appear inside the editorial text.</li>
  <li>The order in which anything is listed on this site.</li>
</ul>
<p>Advertisers have no editorial control here. They cannot see drafts, cannot request changes, and cannot have a page taken down. The separation is structural rather than a matter of goodwill: the advertising is programmatic, so there is no relationship to compromise in the first place.</p>

<h2>Your choices</h2>
<p>You can stop advertising being personalized to you without leaving the site. The controls, including Google Ads Settings, the Digital Advertising Alliance opt-out and the DoubleClick DART cookie opt-out, are listed in full in our <a href="privacy-policy.php">Privacy Policy</a>, and browser-level cookie controls are covered in our <a href="cookie-policy.php">Cookie Policy</a>.</p>
<p>If you use a content blocker, we are not going to nag you about it. There is no wall, no interstitial and no counting of how many pages you have read.</p>

<h2>Questions</h2>
