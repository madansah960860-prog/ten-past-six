<h2>Nutrition figures are estimates</h2>
<p>Every recipe on this site carries an estimated nutrition block. The word estimated is doing real work. The figures are calculated from generic ingredient databases and from the quantities written in the recipe, and they will not match what you actually eat, for several unavoidable reasons.</p>
<ul>
  <li>Ingredients vary. Two onions of the same stated weight differ in sugar content; two cuts of the same meat differ in fat.</li>
  <li>Brands vary enormously, especially for stock, sauces, breads and anything canned.</li>
  <li>Oil absorbed during frying is not the same as oil added to the pan, and we cannot know how much stayed behind.</li>
  <li>Marinades and brines are largely discarded; the databases count them as eaten.</li>
  <li>Portion sizes are nominal. A recipe that serves four serves three hungry people or six moderate ones.</li>
</ul>
<p>Treat the figures as a rough order of magnitude for comparison between recipes, not as a number to build a medical diet on. If a precise figure matters to you clinically, calculate it yourself from the packets in front of you.</p>

<h2>Allergens are your responsibility to check</h2>
<p>Each recipe carries an allergen note listing the major allergens present in the ingredients as written. That note is a courtesy and a starting point, not a guarantee. You must read the label on every product you buy. Formulations change without notice, "may contain" warnings vary between factories, and a substitution you make at home changes the picture entirely. If you or anyone you are cooking for has a diagnosed allergy, the label in your hand beats anything printed on a website.</p>

<h2>Food safety</h2>
<p>Cook to safe internal temperatures, chill leftovers within two hours, keep raw and cooked foods apart, wash your hands and your boards, and do not rely on a recipe's timings alone to tell you that something is done. Timings assume a particular pan on a particular stovetop; yours will differ. Use a probe thermometer for meat, and use your judgment for everything else. Storage advice on each recipe assumes a refrigerator running at or below 5 degrees Celsius.</p>
<ul>
  <li>Poultry: 74 degrees Celsius in the thickest part, juices running clear.</li>
  <li>Minced meat and sausages: 71 degrees Celsius throughout.</li>
  <li>Whole cuts of beef and lamb: 63 degrees Celsius for medium rare, rested.</li>
  <li>Fish: opaque and flaking, roughly 63 degrees Celsius.</li>
  <li>Reheated food: piping hot throughout, 75 degrees Celsius, once only.</li>
</ul>

<h2>Your kitchen is not our kitchen</h2>
<p>Recipes are tested in a domestic kitchen with ordinary equipment, and they are written as carefully as we can manage. Even so, ovens run hot or cold, stovetops differ in power, altitude changes boiling points, and humidity changes how dough behaves. Read a recipe through before starting, and trust what you can see and smell over what the clock says.</p>

