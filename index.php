    <div class="cols cols--2">
      <div>
        <h2>Why this site has no JavaScript</h2>
        <p>Not one line. Not on the recipe pages, not on the index, not even for the filter
          that sorts recipes by time, which is built out of the CSS <code>:target</code>
          selector and about eight lines of stylesheet.</p>
        <p>The reason is entirely practical. You are holding a phone in one hand with the
          other hand covered in oil. A page that loads, then shifts, then loads an
          advertisement that pushes the method down by two hundred pixels, is not a minor
          annoyance in that situation. It is the difference between following a recipe and
          losing your place in it.</p>
        <p>Every advertisement slot on this site has its exact dimensions reserved in the
          stylesheet before anything loads. Nothing on any page moves after it has
          appeared.</p>
      </div>
      <div>
        <h2>And no story before the recipe</h2>
        <p>You already know the argument for the long preamble: search engines reward length,
          and a recipe on its own is thin. That is a real commercial pressure and this site
          simply accepts the cost of ignoring it.</p>
        <p>What you get instead is two sentences of headnote, then the one thing that actually
          determines whether the dish works, then the method. The explanation of why a step
          matters sits inside the step, where you are when you need it, rather than eight
          hundred words above it where you will not read it.</p>
        <p>There is a good deal of writing on this site. It is on the
          <a href="pages/about.php">about page</a> and the
          <a href="pages/categories.php">by time page</a>, where somebody who wants to read
          can find it, and where somebody who is hungry can ignore it.</p>
      </div>
