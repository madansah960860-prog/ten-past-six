      <div>
        <h2>Six things that make weeknight cooking faster</h2>
        <p><strong>Chop before the pan goes on.</strong> Not most of it. All of it. Every
          recipe on this site that takes under fifteen minutes is genuinely unmanageable if
          you are still slicing onion while the garlic is in the pan.</p>
        <p><strong>Get the pan hotter than feels right.</strong> The single most common reason
          a fast recipe fails at home is an underheated pan, which steams instead of browning
          and then everything takes twice as long and tastes of nothing.</p>
        <p><strong>Use a wider pan.</strong> Width is speed. A crowded pan traps steam, and
          twelve inches beats ten by more than the two inches suggests.</p>
        <p><strong>Keep four things in the door of the refrigerator.</strong> Soy sauce, a
          lemon, something pickled, and Parmesan. Between them they finish almost anything.</p>
        <p><strong>Salt the water properly.</strong> Pasta and noodle water should taste of the
          sea. Salt added later never reaches the inside of the noodle.</p>
        <p><strong>Do not clean as you go.</strong> Heretical, and correct. Twenty minutes of
          cooking does not leave enough mess to justify losing attention at the stove.</p>
      </div>
