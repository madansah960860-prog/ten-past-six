    <div class="cols cols--2">
      <div>
        <h2>About the times</h2>
        <p>Every number on this site was measured, not estimated. The recipe gets cooked four
          times. Twice of those are against a stopwatch that starts when I walk into the
          kitchen and stops when the food is on the table, including chopping, including
          waiting for water to boil, including the pause where I could not find the soy
          sauce.</p>
        <p>Then Deb from downstairs cooks the final draft cold, with no explanation from me and
          a timer running. If her time comes out over the number on the card, the number on the
          card changes. It has changed four times out of six.</p>
        <p>That is why one of these says fifteen minutes rather than ten, despite looking like
          a ten-minute recipe. It is not a ten-minute recipe. Chilli paneer takes fifteen and
          pretending otherwise would just make you feel slow.</p>
      </div>
      <div>
        <h2>What is not counted</h2>
        <p><strong>Shopping.</strong> Obviously. Every recipe here lists what you need at the
          top and most of it is pantry.</p>
        <p><strong>Rice you cooked yesterday.</strong> The fried rice needs cold rice. Making
          the rice is not part of the ten minutes and the recipe says so.</p>
        <p><strong>The oven preheating</strong>, for the gnocchi. That is eight minutes on its
          own and it is stated separately rather than hidden inside the total.</p>
        <p>Every one of those exclusions is written on the recipe itself. Nothing is buried.</p>
      </div>
    </div>
  </div>
</section>

